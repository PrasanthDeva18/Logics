// In the Js Ceil Math function 

// rounds up the number into next largest numbers

Math.ceil(0.95);    // 1
Math.ceil(4.00);    // 4 (Integers remain unchanged)
Math.ceil(7.004);   // 8 

// Postive Decimals

Math.ceil(2.1) // 3

// Negative Decimals

Math.ceil(-2.56) // -2

// Strings

Math.ceil("4.3") // 5

Math.ceil("A") // NaN

Math.ceil(null) || Math.ceil("") // 0
